def sub_fallback(links: list[str] | None) -> str:
    if not links:
        return (
            "⚠️ <b>Прямых ключей пока нет.</b>\n"
            "Напишите в поддержку — кнопка «Связаться»."
        )
    lines = "\n\n".join(f"<code>{html.escape(lk)}</code>" for lk in links)
    return (
        "🔧 <b>Подписка не грузится?</b>\n\n"
        "Ссылка-подписка — это файл, который приложение <b>скачивает</b> по интернету "
        "с сервера. Если ваш оператор блокирует доступ именно к этому серверу "
        "(частое дело на мобильном интернете в РФ) — скачивание зависает и "
        "выдаёт таймаут, хотя сам VPN тут ни при чём: он идёт напрямую на другой "
        "сервер и блокировки не касается.\n\n"
        "Ниже — те же самые ключи в готовом виде. Скачивать их не нужно — "
        "просто вставьте в приложение вручную, через «Add from clipboard» / "
        "«Добавить вручную» / «Импорт по ссылке»:\n\n"
        f"{lines}\n\n"
        "⚠️ <b>Важно:</b> если конфигурация сервера когда-нибудь поменяется "
        "(например, заменится нода) — эти конкретные ключи перестанут работать. "
        "Новые нужно будет заново взять здесь же, в боте (кнопка «📊 Моя подписка»).\n\n"
        "💡 <b>Совет:</b> импортируйте один из ключей выше и подключитесь. Как только "
        "VPN заработает — откройте ссылку-подписку ещё раз: теперь она подгрузится "
        "уже через сам VPN, в обход блокировки, и дальше будет обновляться сама."
    )


